def main():
    """
    Main executable workflow for Module 5 Baseline Random Forest.
    """
    # Step 1: Load Data
    split_data = load_split_data()
    if split_data is None:
        return
    X_train, X_val, y_train, y_val = split_data

    # Step 2: Validate Data
    if not validate_split_data(X_train, X_val, y_train, y_val):
        return

    # Step 3: Encode Target
    y_train_encoded, y_val_encoded, label_encoder = encode_target(y_train, y_val)

    # Step 4: Train Baseline Model
    model = train_baseline_model(X_train, y_train_encoded)

    # Step 5: Calculate Metrics
    metrics = calculate_metrics(model, X_train, y_train_encoded, X_val, y_val_encoded)

    # Step 6: Feature Importance
    fi_df = calculate_feature_importance(model)

    # Generate classification report CSV & predictions CSV
    class_names = list(label_encoder.classes_)
    generate_classification_report_csv(y_val_encoded, model.predict(X_val), class_names)
    generate_prediction_results(model, X_val, y_val, label_encoder)

    # Save Model Artifacts
    save_model_artifacts(model, label_encoder, metrics, len(X_train), len(X_val))

    # Reproducibility Test
    reproducible = test_reproducibility(
        X_train, y_train_encoded, X_val, y_val_encoded, metrics
    )

    # Sample Prediction Test
    run_sample_prediction_test(model, X_val, y_val, label_encoder)

    # Baseline Report
    final_status = generate_baseline_report(metrics, fi_df, reproducible)

    print("\n" + "=" * 60)
    print("MODULE 5 COMPLETED")
    print("============================================================")
    print(f"\nFinal Status:\n{final_status}\n")


if __name__ == "__main__":
    main()

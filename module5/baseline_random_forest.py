def load_split_data() -> Optional[Tuple[pd.DataFrame, pd.DataFrame, pd.Series, pd.Series]]:
    """
    Load split datasets generated by Module 4.
    """
    print("=" * 60)
    print("SMART CROP ADVISOR")
    print("MODULE 5 — BASELINE RANDOM FOREST")
    print("=" * 60)
    print("\n[1] Loading Split Data")

    required_paths = [X_TRAIN_PATH, X_VAL_PATH, Y_TRAIN_PATH, Y_VAL_PATH]
    missing_paths = [p for p in required_paths if not p.exists()]

    if missing_paths:
        print("\nERROR:")
        print("Module 4 split data not found.")
        print("\nMissing expected split file(s):")
        for p in missing_paths:
            print(f"  - {p}")
        print("\nPlease complete Module 4 before running Module 5.")
        return None

    try:
        X_train = pd.read_csv(X_TRAIN_PATH)
        X_val = pd.read_csv(X_VAL_PATH)
        y_train = pd.read_csv(Y_TRAIN_PATH)[TARGET_COLUMN]
        y_val = pd.read_csv(Y_VAL_PATH)[TARGET_COLUMN]

        print(f"✓ Training data loaded  : {X_train.shape[0]} samples x {X_train.shape[1]} features")
        print(f"✓ Validation data loaded: {X_val.shape[0]} samples x {X_val.shape[1]} features")
        return X_train, X_val, y_train, y_val
    except Exception as e:
        print(f"\nERROR: Failed to load split CSV files: {e}")
        return None


def validate_split_data(
    X_train: pd.DataFrame, X_val: pd.DataFrame, y_train: pd.Series, y_val: pd.Series
) -> bool:
    """
    Validate features, feature ordering, sample counts, and lack of nulls.
    """
    print("\n[2] Dataset Validation")

    if list(X_train.columns) != FEATURE_COLUMNS or list(X_val.columns) != FEATURE_COLUMNS:
        print("✗ Feature validation: FAIL (Column names or order do not match expected schema)")
        return False

    if len(X_train) != len(y_train) or len(X_val) != len(y_val):
        print("✗ Feature/Target length mismatch: FAIL")
        return False

    if X_train.isnull().sum().sum() > 0 or X_val.isnull().sum().sum() > 0:
        print("✗ Null values found in split dataset: FAIL")
        return False

    print("✓ 6 features verified")
    print("✓ Target verified")
    print("✓ Sample counts verified")
    return True


def encode_target(
    y_train: pd.Series, y_val: pd.Series
) -> Tuple[np.ndarray, np.ndarray, LabelEncoder]:
    """
    Fit LabelEncoder ONLY on training labels, then transform training and validation targets.
    """
    print("\n[3] Target Encoding")
    label_encoder = LabelEncoder()
    y_train_encoded = label_encoder.fit_transform(y_train)

    train_classes = set(label_encoder.classes_)
    val_classes = set(y_val.unique())

    missing_in_train = val_classes - train_classes
    if missing_in_train:
        print(f"✗ Validation contains classes missing in training set: {missing_in_train}")
        raise ValueError(f"Unseen validation crop classes: {missing_in_train}")

    y_val_encoded = label_encoder.transform(y_val)

    print("✓ LabelEncoder fitted on training labels")
    print(f"  - Number of encoded classes: {len(label_encoder.classes_)}")
    print("✓ Validation labels transformed")
    return y_train_encoded, y_val_encoded, label_encoder


def train_baseline_model(
    X_train: pd.DataFrame, y_train_encoded: np.ndarray
) -> RandomForestClassifier:
    """
    Instantiate and train baseline RandomForestClassifier using fixed parameters.
    """
    print("\n[4] Creating & Training Baseline Random Forest")
    for param, val in BASELINE_PARAMS.items():
        print(f"✓ {param:<15} = {val}")

    rf_model = RandomForestClassifier(**BASELINE_PARAMS)
    rf_model.fit(X_train, y_train_encoded)
    print("✓ Random Forest training completed")
    return rf_model


def calculate_metrics(
    model: RandomForestClassifier,
    X_train: pd.DataFrame,
    y_train_encoded: np.ndarray,
    X_val: pd.DataFrame,
    y_val_encoded: np.ndarray,
) -> Dict[str, float]:
    """
    Calculate training and validation performance metrics.
    Prints only Training Accuracy, Validation Accuracy, and Train vs Val Accuracy Gap.
    """
    train_preds = model.predict(X_train)
    train_acc = float(accuracy_score(y_train_encoded, train_preds))
    train_f1_weighted = float(f1_score(y_train_encoded, train_preds, average="weighted"))

    val_preds = model.predict(X_val)
    val_acc = float(accuracy_score(y_val_encoded, val_preds))
    val_prec_weighted = float(precision_score(y_val_encoded, val_preds, average="weighted"))
    val_rec_weighted = float(recall_score(y_val_encoded, val_preds, average="weighted"))
    val_f1_weighted = float(f1_score(y_val_encoded, val_preds, average="weighted"))

    val_prec_macro = float(precision_score(y_val_encoded, val_preds, average="macro"))
    val_rec_macro = float(recall_score(y_val_encoded, val_preds, average="macro"))
    val_f1_macro = float(f1_score(y_val_encoded, val_preds, average="macro"))

    diff_acc = (train_acc - val_acc) * 100

    print("\n[5] Performance Evaluation")
    print(f"Training Accuracy              : {train_acc * 100:.2f}%")
    print(f"Validation Accuracy            : {val_acc * 100:.2f}%")
    print(f"Train vs Validation Accuracy Gap: {diff_acc:.2f}%")

    metrics = {
        "training_accuracy": train_acc,
        "validation_accuracy": val_acc,
        "training_f1_weighted": train_f1_weighted,
        "validation_f1_weighted": val_f1_weighted,
        "validation_precision_weighted": val_prec_weighted,
        "validation_recall_weighted": val_rec_weighted,
        "validation_precision_macro": val_prec_macro,
        "validation_recall_macro": val_rec_macro,
        "validation_f1_macro": val_f1_macro,
        "accuracy_gap": train_acc - val_acc,
    }

    # Save baseline metrics CSV & summary JSON
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    metrics_df = pd.DataFrame(list(metrics.items()), columns=["metric", "value"])
    metrics_df.to_csv(RESULTS_DIR / "baseline_metrics.csv", index=False)

    summary_json = {
        "model": "Baseline Random Forest",
        "optimization": "None",
        "n_estimators": BASELINE_PARAMS["n_estimators"],
        "random_state": BASELINE_PARAMS["random_state"],
        "training_accuracy": train_acc,
        "validation_accuracy": val_acc,
        "validation_f1_weighted": val_f1_weighted,
        "validation_f1_macro": val_f1_macro,
    }

    with open(RESULTS_DIR / "baseline_summary.json", "w", encoding="utf-8") as f:
        json.dump(summary_json, f, indent=4)

    return metrics


def calculate_feature_importance(
    model: RandomForestClassifier
) -> pd.DataFrame:
    """
    Extract model-based feature importances and generate report CSV.
    """
    print("\n[6] Feature Importance")
    importances = model.feature_importances_
    total_imp = sum(importances)

    fi_df = pd.DataFrame({
        "feature": FEATURE_COLUMNS,
        "importance": importances,
        "percentage": (importances / total_imp * 100).round(2),
    }).sort_values(by="importance", ascending=False).reset_index(drop=True)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    fi_csv_path = RESULTS_DIR / "baseline_feature_importance.csv"
    fi_df.to_csv(fi_csv_path, index=False)

    print(f"✓ Saved feature importances CSV to: {fi_csv_path}")
    print("Ranking:")
    for idx, row in fi_df.iterrows():
        print(f"  {idx+1}. {row['feature']:<15} : {row['importance']:.4f} ({row['percentage']}%)")

    return fi_df


def generate_classification_report_csv(
    y_val_encoded: np.ndarray, val_preds: np.ndarray, class_names: List[str]
) -> None:
    """
    Generate detailed per-class classification report CSV.
    """
    report_dict = classification_report(
        y_val_encoded, val_preds, target_names=class_names, output_dict=True
    )
    clf_df = pd.DataFrame(report_dict).transpose().reset_index()
    clf_df.rename(columns={"index": "class_or_metric"}, inplace=True)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    clf_csv_path = RESULTS_DIR / "classification_report.csv"
    clf_df.to_csv(clf_csv_path, index=False)
    print(f"✓ Saved classification report CSV to: {clf_csv_path}")


def generate_prediction_results(
    model: RandomForestClassifier,
    X_val: pd.DataFrame,
    y_val: pd.Series,
    label_encoder: LabelEncoder,
) -> None:
    """
    Generate baseline_predictions.csv detailing actual vs predicted crops and prediction confidence.
    """
    val_preds_num = model.predict(X_val)
    val_preds_str = label_encoder.inverse_transform(val_preds_num)
    val_probs = model.predict_proba(X_val)
    max_probs = np.max(val_probs, axis=1)

    pred_df = X_val.copy()
    pred_df["actual_crop"] = y_val.values
    pred_df["predicted_crop"] = val_preds_str
    pred_df["correct"] = (pred_df["actual_crop"] == pred_df["predicted_crop"])
    pred_df["prediction_confidence"] = max_probs.round(4)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    pred_csv_path = RESULTS_DIR / "baseline_predictions.csv"
    pred_df.to_csv(pred_csv_path, index=False)
    print(f"✓ Validation predictions detailed CSV saved to: {pred_csv_path}")


def save_model_artifacts(
    model: RandomForestClassifier,
    label_encoder: LabelEncoder,
    metrics: Dict[str, float],
    num_train: int,
    num_val: int,
) -> None:
    """
    Serialize model to baseline_rf_model.pkl, label encoder to crop_label_encoder.pkl,
    and save baseline_model_metadata.json.
    """
    MODELS_DIR.mkdir(parents=True, exist_ok=True)

    joblib.dump(model, MODEL_PATH)
    joblib.dump(label_encoder, ENCODER_PATH)

    metadata = {
        "model_type": "RandomForestClassifier",
        "model_purpose": "Baseline crop recommendation classifier prior to GA optimization",
        "feature_names": FEATURE_COLUMNS,
        "target_column": TARGET_COLUMN,
        "num_features": len(FEATURE_COLUMNS),
        "num_classes": len(label_encoder.classes_),
        "classes": list(label_encoder.classes_),
        "hyperparameters": BASELINE_PARAMS,
        "num_training_samples": num_train,
        "num_validation_samples": num_val,
        "created_at": datetime.now().isoformat(),
        "metrics": metrics,
    }

    with open(METADATA_PATH, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=4)

    print("\nModel saved successfully.")


def run_sample_prediction_test(
    model: RandomForestClassifier,
    X_val: pd.DataFrame,
    y_val: pd.Series,
    label_encoder: LabelEncoder,
) -> None:
    """
    Perform a single validation sample inference test.
    """
    print("\n[7] Sample Prediction Test")
    sample_input = X_val.iloc[[0]]
    actual = y_val.iloc[0]

    pred_num = model.predict(sample_input)[0]
    pred_crop = label_encoder.inverse_transform([pred_num])[0]
    prob = float(np.max(model.predict_proba(sample_input)))

    print("Sample Input Parameters:")
    for col in FEATURE_COLUMNS:
        print(f"  - {col:<15} : {sample_input[col].values[0]}")
    print(f"Actual Crop             : {actual}")
    print(f"Predicted Crop          : {pred_crop}")
    print(f"Prediction Probability  : {prob * 100:.2f}%")


def test_reproducibility(
    X_train: pd.DataFrame,
    y_train_encoded: np.ndarray,
    X_val: pd.DataFrame,
    y_val_encoded: np.ndarray,
    initial_metrics: Dict[str, float],
) -> bool:
    """
    Train a second model instance with seed=42 and verify exact metric matching.
    """
    rf2 = RandomForestClassifier(**BASELINE_PARAMS)
    rf2.fit(X_train, y_train_encoded)
    preds2 = rf2.predict(X_val)
    acc2 = float(accuracy_score(y_val_encoded, preds2))
    f12 = float(f1_score(y_val_encoded, preds2, average="weighted"))

    is_reproducible = (
        acc2 == initial_metrics["validation_accuracy"]
        and f12 == initial_metrics["validation_f1_weighted"]
    )
    return is_reproducible



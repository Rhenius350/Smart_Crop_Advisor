import React, { useEffect, useState } from 'react';
import { Layers, Database, ShieldCheck, FileText, CheckCircle2, AlertCircle } from 'lucide-react';
import { getResearchData } from '../services/api';

const Research = () => {
  const [researchInfo, setResearchInfo] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    const fetchResearch = async () => {
      setLoading(true);
      try {
        const data = await getResearchData();
        setResearchInfo(data);
      } catch (err) {
        setError(err.message || 'Failed to load research metadata.');
      } finally {
        setLoading(false);
      }
    };

    fetchResearch();
  }, []);

  if (loading) {
    return (
      <div style={{ textAlign: 'center', padding: '4rem 2rem' }}>
        <div className="spinner" style={{ margin: '0 auto 1rem auto' }}></div>
        <p style={{ color: 'var(--text-sub)' }}>Loading Pipeline Research Metadata...</p>
      </div>
    );
  }

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '2.5rem' }}>
      {/* Header */}
      <div className="section-header">
        <h1 className="section-title" style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', gap: '0.75rem' }}>
          <Layers color="var(--primary)" size={32} />
          <span>Research Pipeline Metadata</span>
        </h1>
        <p className="section-subtitle">
          Detailed breakdown of dataset splits, serialized model artifacts, and evaluation reports generated by Modules 1 through 9.
        </p>
      </div>

      {error && (
        <div style={{ background: 'rgba(239, 68, 68, 0.1)', border: '1px solid var(--accent-red)', padding: '1rem', borderRadius: 'var(--radius-md)', color: 'var(--accent-red)', display: 'flex', alignItems: 'center', gap: '0.6rem' }}>
          <AlertCircle size={20} />
          <span>{error}</span>
        </div>
      )}

      {/* Dataset & Split Info Cards */}
      <div className="grid-2">
        <div className="card">
          <div className="card-header">
            <h3 className="card-title">
              <Database className="title-icon" size={20} />
              <span>Dataset Split Partitioning</span>
            </h3>
            <span className="badge badge-info">Stratified 80 / 20 Split</span>
          </div>

          <div style={{ display: 'flex', flexDirection: 'column', gap: '0.8rem', fontSize: '0.95rem' }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', padding: '0.5rem 0', borderBottom: '1px solid var(--border-color)' }}>
              <span style={{ color: 'var(--text-muted)' }}>Total Dataset Samples</span>
              <strong>{researchInfo?.dataset?.total_samples || 2200} Rows</strong>
            </div>
            <div style={{ display: 'flex', justifyContent: 'space-between', padding: '0.5rem 0', borderBottom: '1px solid var(--border-color)' }}>
              <span style={{ color: 'var(--text-muted)' }}>Training Set (80%)</span>
              <strong style={{ color: 'var(--primary)' }}>{researchInfo?.dataset?.training_samples || 1760} Samples</strong>
            </div>
            <div style={{ display: 'flex', justifyContent: 'space-between', padding: '0.5rem 0', borderBottom: '1px solid var(--border-color)' }}>
              <span style={{ color: 'var(--text-muted)' }}>Validation Set (20%)</span>
              <strong style={{ color: 'var(--accent-cyan)' }}>{researchInfo?.dataset?.validation_samples || 440} Samples</strong>
            </div>
            <div style={{ display: 'flex', justifyContent: 'space-between', padding: '0.5rem 0', borderBottom: '1px solid var(--border-color)' }}>
              <span style={{ color: 'var(--text-muted)' }}>Supported Crop Classes</span>
              <strong>{researchInfo?.dataset?.num_classes || 22} Classes</strong>
            </div>
            <div style={{ display: 'flex', justifyContent: 'space-between', padding: '0.5rem 0' }}>
              <span style={{ color: 'var(--text-muted)' }}>Random Seed (Reproducibility)</span>
              <strong>random_state = 42</strong>
            </div>
          </div>
        </div>

        <div className="card">
          <div className="card-header">
            <h3 className="card-title">
              <FileText className="title-icon" color="var(--accent-cyan)" size={20} />
              <span>Serialized Model Artifacts</span>
            </h3>
            <span className="badge badge-success">Saved in models/</span>
          </div>

          <div style={{ display: 'flex', flexDirection: 'column', gap: '0.8rem', fontSize: '0.9rem' }}>
            <div style={{ background: 'var(--bg-input)', padding: '0.75rem 1rem', borderRadius: 'var(--radius-sm)', border: '1px solid var(--border-color)' }}>
              <div style={{ fontWeight: 700, color: 'var(--primary)' }}>ga_optimized_rf_model.pkl</div>
              <div style={{ fontSize: '0.8rem', color: 'var(--text-muted)' }}>GA-Optimized Random Forest binary (265 estimators, ~10 MB)</div>
            </div>

            <div style={{ background: 'var(--bg-input)', padding: '0.75rem 1rem', borderRadius: 'var(--radius-sm)', border: '1px solid var(--border-color)' }}>
              <div style={{ fontWeight: 700, color: 'var(--text-sub)' }}>crop_label_encoder.pkl</div>
              <div style={{ fontSize: '0.8rem', color: 'var(--text-muted)' }}>LabelEncoder fitted on y_train (22 crop classes)</div>
            </div>

            <div style={{ background: 'var(--bg-input)', padding: '0.75rem 1rem', borderRadius: 'var(--radius-sm)', border: '1px solid var(--border-color)' }}>
              <div style={{ fontWeight: 700, color: 'var(--text-muted)' }}>baseline_rf_model.pkl</div>
              <div style={{ fontSize: '0.8rem', color: 'var(--text-muted)' }}>Baseline reference Random Forest binary (100 estimators, ~5.5 MB)</div>
            </div>
          </div>
        </div>
      </div>

      {/* Modules 1 to 9 Verification Table */}
      <div className="card">
        <div className="card-header">
          <h3 className="card-title">Pipeline Module Verification Status</h3>
          <span className="badge badge-success">100% Deterministic PASS</span>
        </div>

        <div style={{ display: 'grid', gridTemplateColumns: 'repeat(3, 1fr)', gap: '1rem', marginTop: '1rem' }}>
          {researchInfo?.modules?.map((m, idx) => (
            <div key={idx} style={{ background: 'var(--bg-input)', padding: '1rem', borderRadius: 'var(--radius-md)', border: '1px solid var(--border-color)' }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '0.3rem' }}>
                <span style={{ fontSize: '0.8rem', fontWeight: 800, color: 'var(--primary)' }}>{m.name}</span>
                <span className="badge badge-success" style={{ fontSize: '0.7rem' }}>
                  <CheckCircle2 size={12} /> {m.status}
                </span>
              </div>
              <div style={{ fontWeight: 700, fontSize: '0.95rem' }}>{m.title}</div>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
};

export default Research;
